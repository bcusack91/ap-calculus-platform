#!/usr/bin/env node
/**
 * Generates the per-lesson aggregator modules the manifest's importPath points
 * at. gen-registry-extra.cjs emits loaders shaped
 * `import(importPath).then((m) => m.parts[i])`, so every lesson needs ONE module
 * exporting `parts: LessonData[]` in part order. The MCAT subtopic lessons are
 * authored as separate per-part files, so each aggregator just re-exports them.
 *
 * Reads the same manifest gen-registry-extra.cjs reads; writes one
 * `<importPath>.ts` per entry whose parts live in `<importPath>-part<N>.ts`.
 * Idempotent — safe to re-run after adding lessons.
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const DIR = path.join(ROOT, 'src/data/interactive-lessons')
const MANIFEST = path.join(DIR, 'lessons-manifest.json')

const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'))

let written = 0
let skipped = 0
for (const entry of manifest) {
  const base = entry.importPath.replace(/^\.\//, '')
  const partFiles = entry.partTitles.map((_, i) => `${base}-part${i + 1}.ts`)
  // Only lessons authored as split part files need an aggregator; lessons that
  // already ship a single module with its own `parts` export are left alone.
  if (!partFiles.every((f) => fs.existsSync(path.join(DIR, f)))) {
    skipped++
    continue
  }

  const imports = []
  const names = []
  partFiles.forEach((file, i) => {
    const src = fs.readFileSync(path.join(DIR, file), 'utf8')
    const match = src.match(/export\s+const\s+(\w+)\s*[:=]/)
    if (!match) throw new Error(`no named export found in ${file}`)
    const local = `part${i + 1}`
    imports.push(`import { ${match[1]} as ${local} } from './${file.replace(/\.ts$/, '')}'`)
    names.push(local)
  })

  const out = `import type { LessonData } from './registry'
${imports.join('\n')}

/**
 * AUTO-GENERATED by scripts/gen-mcat-lesson-aggregators.cjs.
 * Do not edit by hand — edit the part files and re-run the generator.
 */
export const parts: LessonData[] = [${names.join(', ')}]
`
  fs.writeFileSync(path.join(DIR, `${base}.ts`), out)
  written++
}

console.log(`wrote ${written} aggregator module(s); skipped ${skipped} entry(ies) without split part files`)
