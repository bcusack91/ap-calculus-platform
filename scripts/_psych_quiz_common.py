#!/usr/bin/env python3
"""
Shared render helpers for AP Psychology entrance quiz generators.
Used by scripts/write-psych-entrance-quizzes-batch{1..4}.py.
"""
from __future__ import annotations
import os, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "src", "data", "entrance-quizzes")

PART_TITLES = {
    1: "Core Concepts",
    2: "Key Processes",
    3: "Patterns & Examples",
    4: "Connections & Interactions",
    5: "Change Over Time",
    6: "Problem-Solving Workshop",
    7: "AP Review",
}


def render(slug: str, data: dict) -> str:
    title = data["title"]
    prefix = data["prefix"]
    qs = data["qs"]
    assert len(qs) == 14, f"{slug}: need 14 questions, got {len(qs)}"

    lines = []
    for idx, (q, opts, correct, expl) in enumerate(qs):
        part_num = (idx // 2) + 1
        sub = "a" if idx % 2 == 0 else "b"
        qid = f"{prefix}-ent-{part_num}{sub}"
        opts_js = json.dumps(opts, ensure_ascii=False)
        lines.append(
            f"  {{ id: {json.dumps(qid)}, question: {json.dumps(q, ensure_ascii=False)}, "
            f"options: {opts_js}, correctIndex: {correct}, "
            f"explanation: {json.dumps(expl, ensure_ascii=False)}, "
            f"partNumber: {part_num}, partTitle: {json.dumps(PART_TITLES[part_num])} }}"
        )

    body = ",\n".join(lines)
    return (
        f"/**\n"
        f" * Entrance Quiz — {title} (AP Psychology)\n"
        f" * 14 questions · 7 parts (2 per part)\n"
        f" * AUTO-GENERATED by scripts/write-psych-entrance-quizzes-batch*.py\n"
        f" */\n\n"
        f"import type {{ EntranceQuizQuestion }} from './moles-molar-mass'\n\n"
        f"const questions: EntranceQuizQuestion[] = [\n{body}\n]\n\n"
        f"export function generateEntranceQuiz(): EntranceQuizQuestion[] {{\n"
        f"  return [...questions].sort(() => Math.random() - 0.5)\n"
        f"}}\n\n"
        f"export function getEntranceQuizParts(): {{ partNumber: number; partTitle: string }}[] {{\n"
        f"  return [\n"
        f"    {{ partNumber: 1, partTitle: 'Core Concepts' }},\n"
        f"    {{ partNumber: 2, partTitle: 'Key Processes' }},\n"
        f"    {{ partNumber: 3, partTitle: 'Patterns & Examples' }},\n"
        f"    {{ partNumber: 4, partTitle: 'Connections & Interactions' }},\n"
        f"    {{ partNumber: 5, partTitle: 'Change Over Time' }},\n"
        f"    {{ partNumber: 6, partTitle: 'Problem-Solving Workshop' }},\n"
        f"    {{ partNumber: 7, partTitle: 'AP Review' }}\n"
        f"  ]\n"
        f"}}\n"
    )


def write_batch(T: dict, expected_slugs: set):
    missing = expected_slugs - set(T)
    extra = set(T) - expected_slugs
    if missing:
        raise SystemExit(f"Missing topics: {missing}")
    if extra:
        raise SystemExit(f"Unexpected topics: {extra}")

    prefixes = [d["prefix"] for d in T.values()]
    if len(set(prefixes)) != len(prefixes):
        dup = [p for p in prefixes if prefixes.count(p) > 1]
        raise SystemExit(f"Duplicate prefixes within batch: {set(dup)}")

    for slug, data in T.items():
        path = os.path.join(OUT_DIR, f"{slug}.ts")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(slug, data))
        print(f"Wrote {path}")
    print(f"\nDone: {len(T)} entrance quiz files.")
