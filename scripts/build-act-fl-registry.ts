/**
 * Regenerate src/data/act-practice/full-length/forms.generated.ts from the
 * full-length section files that exist on disk (fl<N>-<section>.ts).
 *
 *   npx tsx scripts/build-act-fl-registry.ts          # write the manifest
 *   npx tsx scripts/build-act-fl-registry.ts --check  # exit 1 if it is stale
 *
 * `npm run build` runs it first (the "prebuild" script), so a deploy picks up
 * every section file that exists.
 *
 * The manifest only lists LOADERS (lazy `import()`s, so Next can analyze
 * them and nothing loads until a form is used). Whether a form is offered is
 * decided at runtime by the registry (index.ts): all four sections present
 * and passing the blueprint checks. So a writer finishing a section file just
 * needs this script re-run; a half-finished form stays "coming soon".
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import path from 'path'

const DIR = path.resolve(__dirname, '../src/data/act-practice/full-length')
const OUT = path.join(DIR, 'forms.generated.ts')
const SECTIONS = ['english', 'math', 'reading', 'science'] as const
const FILE_RE = /^fl(\d+)-(english|math|reading|science)\.ts$/

export function manifestSource(files: string[]): string {
  const byForm = new Map<number, Set<string>>()
  for (const f of files) {
    const m = FILE_RE.exec(f)
    if (!m) continue
    const n = Number(m[1])
    if (!byForm.has(n)) byForm.set(n, new Set())
    byForm.get(n)!.add(m[2])
  }
  const forms = [...byForm.keys()].sort((a, b) => a - b)
  const lines = [
    '// AUTO-GENERATED by scripts/build-act-fl-registry.ts. Do not edit by hand:',
    '// run `npx tsx scripts/build-act-fl-registry.ts` after adding a section file.',
    "import type { ActFlLoaderMap } from './loader-types'",
    '',
    'export const ACT_FL_LOADERS: ActFlLoaderMap = {',
  ]
  for (const n of forms) {
    const have = byForm.get(n)!
    lines.push(`  ${n}: {`)
    for (const s of SECTIONS) {
      if (have.has(s)) lines.push(`    ${s}: () => import('./fl${n}-${s}'),`)
    }
    lines.push('  },')
  }
  lines.push('}', '')
  return lines.join('\n')
}

function main() {
  const files = readdirSync(DIR)
  const next = manifestSource(files)
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* first run */
  }
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('forms.generated.ts is stale: run `npx tsx scripts/build-act-fl-registry.ts`.')
      process.exit(1)
    }
    console.log('forms.generated.ts is up to date.')
    return
  }
  if (current === next) {
    console.log('forms.generated.ts already up to date.')
    return
  }
  writeFileSync(OUT, next)
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`)
}

if (typeof require !== 'undefined' && require.main === module) main()
