/**
 * Rebuild src/data/flashcard-checks/topics/index.ts from the topic files in
 * that folder (one per topic slug). Run after adding a topic's questions, once
 * the file has passed validate.ts and the blind solve.
 *
 *   npx tsx scripts/flashcard-checks/register.ts
 */
import { readdirSync, writeFileSync } from 'fs'
import { join } from 'path'

const dir = join(__dirname, '../../src/data/flashcard-checks/topics')
const slugs = readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.slice(0, -3)).sort()
const lines = [
  "import type { CardCheck } from '@/lib/flashcard-check-core'",
  ...slugs.map((s, i) => `import { checks as t${i} } from './${s}'`),
  '',
  '/**',
  ' * Card-check questions for each topic\'s own cards, by topic slug.',
  ' * GENERATED by scripts/flashcard-checks/register.ts: do not edit by hand.',
  ' */',
  'export const TOPIC_CHECKS: Record<string, Record<string, CardCheck>> = {',
  ...slugs.map((s, i) => `  '${s}': t${i},`),
  '}',
  '',
]
writeFileSync(join(dir, 'index.ts'), lines.join('\n'))
console.log('registered', slugs.length, 'topics')
