import { describe, it, expect } from 'vitest'
import fs from 'fs'
import path from 'path'
import { unitsForCourse, coursesWithUnitTests } from '@/lib/unit-tests/course-units'
import { unitTestRouteFor, frqRouteFor } from '@/lib/course-activity-routes'

const GENERATED = [
  'src/lib/unit-tests/course-units.ts',
  'src/lib/course-activity-routes.ts',
]

const read = (rel: string) => fs.readFileSync(path.join(process.cwd(), rel), 'utf8')

describe('generated course lookups stay literal', () => {
  // The configs in src/data/unit-tests/ each carry a full question pool.
  // A lookup that imported them would pull every pool into one module, which
  // is enough to run the production build out of memory — it already did once.
  // Regenerate with scripts/gen-course-lookups.ts instead of hand-editing
  // these into imports.
  it.each(GENERATED)('%s imports nothing from src/data', (rel) => {
    const src = read(rel)
    expect(src).not.toMatch(/from\s+['"]@\/data\//)
    expect(src).not.toMatch(/from\s+['"].*\/data\/unit-tests/)
    expect(src).not.toMatch(/\bimport\s*\(/)
  })

  it.each(GENERATED)('%s is marked auto-generated', (rel) => {
    expect(read(rel)).toContain('AUTO-GENERATED by scripts/gen-course-lookups.ts')
  })
})

describe('course lookups cover the catalogue', () => {
  it('includes the programmatically-built courses', () => {
    // sat-prep and mcat-prep compute their units from domain data rather than
    // declaring them, so a source-text scrape missed them entirely and their
    // unit picker silently fell back to "any unit".
    expect(unitsForCourse('sat-prep').length).toBeGreaterThan(0)
    expect(unitsForCourse('mcat-prep').length).toBeGreaterThan(0)
  })

  it('covers a broad set of courses with real units', () => {
    const courses = coursesWithUnitTests()
    expect(courses.length).toBeGreaterThanOrEqual(35)
    for (const slug of courses) {
      const units = unitsForCourse(slug)
      expect(units.length).toBeGreaterThan(0)
      for (const u of units) {
        expect(u.id).toBeTruthy()
        expect(u.name).toBeTruthy()
      }
    }
  })

  it('resolves activity routes for assignable courses', () => {
    expect(unitTestRouteFor('ap-biology')).toBe('/ap-bio-unit-tests')
    expect(frqRouteFor('ap-biology')).toBe('/ap-bio-frq')
    expect(unitTestRouteFor(null)).toBeNull()
    expect(frqRouteFor('not-a-course')).toBeNull()
  })
})
